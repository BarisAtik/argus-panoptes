"""Simulations that justify the evaluation design, runnable without any model or data.

    python -m forge.simulate --out docs/ci_coverage_simulation.md

Two questions, answered on synthetic speakers whose true WER is known:
1. Coverage: how often does a nominal 95% interval contain the truth if we bootstrap clips,
   versus speakers?
2. Sample size: how many speakers are needed to detect a WER difference between two models?
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from forge.report import markdown_table
from forge.stats import paired_ratio_difference, ratio_ci

WORDS_PER_CLIP = 10


def _logit(p: float) -> float:
    return float(np.log(p / (1 - p)))


def simulate_speakers(
    n_speakers, clips_per_speaker, base_wer, speaker_sd, rng, delta=0.0,
    shared_errors=0.7, delta_sd=0.03,
):
    """Two systems on the same clips. Speakers differ in difficulty (a logit random effect).

    A share `shared_errors` of words are hard for both systems. The rest fail independently,
    and the true difference varies per speaker (`delta_sd`), because model B will not be better
    for everybody. Without these two, B's errors are a superset of A's and every test has
    perfect power, which would be a bug in the simulation, not a finding.
    """
    effect = rng.normal(0, speaker_sd, n_speakers)
    n_clips = rng.poisson(clips_per_speaker - 1, n_speakers) + 1
    speakers = np.repeat(np.arange(n_speakers), n_clips)
    clip_noise = rng.normal(0, 0.3, len(speakers))  # clip difficulty, shared by both systems
    logits = _logit(base_wer) + effect[speakers] + clip_noise
    p_a = 1 / (1 + np.exp(-logits))
    speaker_delta = rng.normal(delta, delta_sd, n_speakers)
    p_b = np.clip(p_a + speaker_delta[speakers], 0, 1)
    u_a = rng.random((len(speakers), WORDS_PER_CLIP))
    fresh = rng.random(u_a.shape)
    u_b = np.where(rng.random(u_a.shape) < shared_errors, u_a, fresh)
    errors_a = (u_a < p_a[:, None]).sum(axis=1).astype(float)
    errors_b = (u_b < p_b[:, None]).sum(axis=1).astype(float)
    return speakers, errors_a, errors_b, np.full(len(speakers), float(WORDS_PER_CLIP))


def true_wer(base_wer, speaker_sd, rng, draws=2_000_000):
    logits = _logit(base_wer) + rng.normal(0, speaker_sd, draws) + rng.normal(0, 0.3, draws)
    return float((1 / (1 + np.exp(-logits))).mean())


def coverage_experiment(n_sims=800, base_wer=0.15, speaker_sd=0.7, seed=7) -> list[dict]:
    rng = np.random.default_rng(seed)
    truth = true_wer(base_wer, speaker_sd, rng)
    rows = []
    for n_speakers, clips in [(30, 3), (30, 15), (100, 3), (100, 15), (300, 5)]:
        hit_clip = hit_speaker = 0
        width_clip, width_speaker = [], []
        for sim in range(n_sims):
            sp, err, _, den = simulate_speakers(n_speakers, clips, base_wer, speaker_sd, rng)
            naive = ratio_ci(err, den, None, n_boot=400, seed=sim)
            cluster = ratio_ci(err, den, sp, n_boot=400, seed=sim)
            hit_clip += naive.low <= truth <= naive.high
            hit_speaker += cluster.low <= truth <= cluster.high
            width_clip.append(naive.high - naive.low)
            width_speaker.append(cluster.high - cluster.low)
        rows.append({
            "speakers": n_speakers,
            "clips/speaker": clips,
            "coverage (clip bootstrap)": hit_clip / n_sims,
            "coverage (speaker bootstrap)": hit_speaker / n_sims,
            "CI width (clip)": float(np.mean(width_clip)),
            "CI width (speaker)": float(np.mean(width_speaker)),
        })
    return rows


def power_experiment(n_sims=300, base_wer=0.15, speaker_sd=0.7, seed=11) -> list[dict]:
    rng = np.random.default_rng(seed)
    rows = []
    for delta in (0.005, 0.01, 0.02):
        for n_speakers in (30, 100, 300):
            detected = 0
            for sim in range(n_sims):
                sp, a, b, den = simulate_speakers(n_speakers, 5, base_wer, speaker_sd, rng, delta)
                result = paired_ratio_difference(a, b, den, sp, n_boot=400, seed=sim)
                detected += result.high < 0  # interval excludes zero, in the right direction
            rows.append({
                "true WER difference": delta,
                "speakers": n_speakers,
                "clips": n_speakers * 5,
                "power": detected / n_sims,
            })
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("docs/ci_coverage_simulation.md"))
    parser.add_argument("--sims", type=int, default=800)
    args = parser.parse_args()
    coverage = coverage_experiment(args.sims)
    power = power_experiment(max(100, args.sims // 3))
    text = f"""# Simulation: why ASR intervals must resample speakers

Generated by `python -m forge.simulate --sims {args.sims}`. **Synthetic speakers, not speech
data:** true WER is known by construction (base 15%, 10-word clips, speaker difficulty as a
logit random effect with SD 0.7, clip difficulty SD 0.3, 70% of errors shared by both models,
per-speaker SD 0.03 on the difference). These values are assumptions; replace them once real
per-speaker variance has been measured.

## Coverage of nominal 95% intervals

{markdown_table(coverage)}
## Power to detect a difference between two models (paired, speaker bootstrap, 5 clips/speaker)

{markdown_table(power)}
"""
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
